/**
 * Builds Uniwind's CSS entry (`global.css`) from the palettes shared with the
 * web (`packages/shared/src/themes.ts`), so the two never drift: every theme
 * becomes an `@variant` with one `--color-*` variable per palette token, named
 * like the web's (`signalPale` → `--color-signal-pale`, class `bg-signal-pale`).
 *
 * `metro.config.js` runs this on every Metro start (dev server and export),
 * so `global.css` is a build artifact and stays out of git. Node strips the
 * types when it loads `themes.ts`, which imports nothing.
 */
const fs = require("node:fs");
const path = require("node:path");

const { themes, cssVariableName } = require("../packages/shared/src/themes.ts");

/** Uniwind registers light and dark itself; the rest go to `extraThemes`. */
const extraThemes = Object.keys(themes).filter(
  (name) => name !== "light" && name !== "dark",
);

function themeCss() {
  const variants = Object.entries(themes).map(([name, theme]) => {
    const lines = Object.entries(theme.colors).map(
      ([token, value]) => `      ${cssVariableName(token)}: ${value};`,
    );
    return `    @variant ${name} {\n${lines.join("\n")}\n    }`;
  });
  return `/* Generated by themeCss.js from packages/shared/src/themes.ts. Do not edit. */
@import "tailwindcss";
@import "uniwind";

/* Registers the font utilities (font-display, font-utility); the platform variants below set them. */
@theme {
  --font-display: "sans-serif";
  --font-utility: "monospace";
}

@layer theme {
  :root {
${variants.join("\n")}

    /* The web's font roles; phones lack the web fonts, so each maps to a close system font. */
    @variant ios {
      --font-display: "Trebuchet MS";
      --font-utility: "Menlo";
    }
    @variant android {
      --font-display: "sans-serif";
      --font-utility: "monospace";
    }
  }
}
`;
}

/** Writes `global.css` next to this file, only when its content changed. */
function writeGlobalCss() {
  const file = path.join(__dirname, "global.css");
  const css = themeCss();
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (current !== css) fs.writeFileSync(file, css);
}

module.exports = { extraThemes, themeCss, writeGlobalCss };
