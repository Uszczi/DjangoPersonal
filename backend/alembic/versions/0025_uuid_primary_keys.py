def _mapped(
    row: Row, table: sa.Table, references: dict[str, str], new_ids: dict[str, dict[int, UUID]]
) -> Row:
    out: Row = {}
    for column in table.columns:
        value = row[column.name]
        if column.name == 'id':
            value = new_ids[table.name][value]
        elif column.name in references and value is not None:
            value = new_ids[references[column.name]][value]
        out[column.name] = value
    return out


def _parents_first(folders: list[Row]) -> list[Row]:
    """Folders ordered so each comes after its parent (the foreign key is checked per row)."""
    by_id = {row['id']: row for row in folders}
    placed: set[int] = set()
    ordered: list[Row] = []

    def place(row: Row) -> None:
        if row['id'] in placed:
            return
        parent = row['parent_id']
        if parent is not None and parent in by_id:
            place(by_id[parent])
        placed.add(row['id'])
        ordered.append(row)

    for row in folders:
        place(row)
    return ordered


